"""Weak attached oblique shocks for a calorically perfect gas.

NASA Glenn (https://www.grc.nasa.gov/www/BGH/oblique.html) and NACA 1135
(https://digital.library.unt.edu/ark:/67531/metadc65650/) document the
underlying relations. SciPy is used for bounded root finding; no CFD data
are generated by this module.
"""
from dataclasses import dataclass, asdict
from math import asin, atan, atan2, cos, degrees, isfinite, pi, radians, sin, sqrt, tan
from scipy.optimize import brentq, minimize_scalar
import argparse
import json

class NoAttachedShock(ValueError):
    """Turning angle exceeds the maximum admitting an attached oblique shock."""

@dataclass(frozen=True)
class ShockState:
    mach_1: float
    theta_deg: float
    gamma: float
    mach_angle_deg: float
    theta_max_deg: float
    shock_angle_deg: float
    p2_p1: float
    rho2_rho1: float
    t2_t1: float
    mach_2: float
    normal_mach_1: float
    normal_mach_2: float
    status: str = "ANALYTICAL_SOLVED"

    def as_dict(self):
        return asdict(self)


def _validate(mach: float, gamma: float, theta: float | None = None):
    if not all(isfinite(v) for v in ((mach, gamma) if theta is None else (mach, gamma, theta))):
        raise ValueError("Inputs must be finite")
    if mach <= 1:
        raise ValueError("Upstream Mach number must exceed 1")
    if gamma <= 1:
        raise ValueError("gamma must exceed 1")
    if theta is not None and not (0 <= theta < 90):
        raise ValueError("theta must be in [0, 90) degrees")


def _turn_angle(beta_rad: float, mach: float, gamma: float) -> float:
    """Deflection theta as a function of shock angle beta (radians)."""
    s = sin(beta_rad)
    numerator = 2.0 * (mach * mach * s * s - 1.0) / tan(beta_rad)
    denominator = mach * mach * (gamma + cos(2 * beta_rad)) + 2.0
    return atan2(numerator, denominator)


def _theta_peak(mach: float, gamma: float):
    _validate(mach, gamma)
    mu = asin(1.0 / mach)
    res = minimize_scalar(lambda beta: -_turn_angle(beta, mach, gamma),
                          bounds=(mu, pi/2), method="bounded",
                          options={"xatol": 1e-13})
    if not res.success:
        raise RuntimeError("Could not determine theta_max")
    return res.x, _turn_angle(res.x, mach, gamma)


def max_deflection_deg(mach: float, gamma: float = 1.4) -> float:
    """Largest theta (degrees) admitting an attached shock for M and gamma."""
    return degrees(_theta_peak(mach, gamma)[1])


def solve_weak_shock(mach: float, theta_deg: float, gamma: float = 1.4) -> ShockState:
    """Find the weak shock root and thermodynamic jumps.

    theta=0 represents the limit of a Mach wave, not a finite-strength shock.
    theta=theta_max represents the coalesced weak/strong root.
    """
    _validate(mach, gamma, theta_deg)
    peak_beta, peak_theta = _theta_peak(mach, gamma)
    theta = radians(theta_deg)
    mu = asin(1.0 / mach)
    if theta > peak_theta + 1e-11:
        raise NoAttachedShock(
            f"NO_ATTACHED_SOLUTION: theta={theta_deg:.6f} deg exceeds "
            f"theta_max={degrees(peak_theta):.6f} deg for M1={mach:g}")
    if theta <= 1e-13:
        beta = mu
    elif abs(theta - peak_theta) <= 1e-11:
        beta = peak_beta
    else:
        beta = brentq(lambda b: _turn_angle(b, mach, gamma) - theta,
                      mu, peak_beta, xtol=1e-14)
    mn1 = mach * sin(beta)
    mn1_sq = mn1**2
    pressure = 1.0 + (2*gamma/(gamma+1)) * (mn1_sq - 1)
    density = ((gamma+1)*mn1_sq)/((gamma-1)*mn1_sq + 2)
    temperature = pressure / density
    mn2_sq = (1 + (gamma-1)*mn1_sq/2)/(gamma*mn1_sq-(gamma-1)/2)
    mn2 = sqrt(mn2_sq)
    downstream_mach = mn2 / sin(beta-theta)
    return ShockState(
        mach_1=mach, theta_deg=theta_deg, gamma=gamma,
        mach_angle_deg=degrees(mu), theta_max_deg=degrees(peak_theta),
        shock_angle_deg=degrees(beta), p2_p1=pressure,
        rho2_rho1=density, t2_t1=temperature, mach_2=downstream_mach,
        normal_mach_1=mn1, normal_mach_2=mn2,
        status="MACH_WAVE_LIMIT" if theta_deg == 0 else "ANALYTICAL_SOLVED")


def main():
    parser = argparse.ArgumentParser(description="Analytical weak oblique-shock reference")
    parser.add_argument("--mach", type=float, default=2.0)
    parser.add_argument("--theta", type=float, default=10.0, help="deflection, degrees")
    parser.add_argument("--gamma", type=float, default=1.4)
    parser.add_argument("--output", help="write JSON to this path")
    args = parser.parse_args()
    try:
        result = solve_weak_shock(args.mach, args.theta, args.gamma).as_dict()
    except NoAttachedShock as error:
        result = {"mach_1": args.mach, "theta_deg": args.theta, "gamma": args.gamma,
                  "status": "NO_ATTACHED_SOLUTION", "reason": str(error),
                  "theta_max_deg": max_deflection_deg(args.mach, args.gamma)}
    payload = json.dumps(result, indent=2) + "\n"
    if args.output:
        from pathlib import Path
        Path(args.output).write_text(payload, encoding="utf-8")
    print(payload, end="")

if __name__ == "__main__":
    main()
